'use client'

import { AssessmentResult } from '@/types'

export async function generatePDF(result: AssessmentResult, childInfo: { childClass: string; childBoard: string }) {
  const { jsPDF } = await import('jspdf')
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' })

  const navy = [26, 26, 46] as const
  const orange = [243, 156, 18] as const
  const white = [255, 255, 255] as const
  const lightGrey = [245, 247, 255] as const
  const darkText = [30, 30, 50] as const

  const pageW = doc.internal.pageSize.getWidth()

  // Header bar
  doc.setFillColor(...navy)
  doc.rect(0, 0, pageW, 28, 'F')

  doc.setTextColor(...white)
  doc.setFontSize(22)
  doc.setFont('helvetica', 'bold')
  doc.text('Immpact', 15, 18)

  doc.setFontSize(10)
  doc.setFont('helvetica', 'normal')
  doc.text('Parent Career Guidance Assessment Report', pageW - 15, 18, { align: 'right' })

  // Profile badge
  doc.setFillColor(...orange)
  doc.roundedRect(15, 35, pageW - 30, 22, 3, 3, 'F')
  doc.setTextColor(...white)
  doc.setFontSize(14)
  doc.setFont('helvetica', 'bold')
  doc.text(result.profile.name, pageW / 2, 44, { align: 'center' })
  doc.setFontSize(9)
  doc.setFont('helvetica', 'normal')
  doc.text(`Overall Score: ${result.percentage}%`, pageW / 2, 52, { align: 'center' })

  // Child info
  doc.setFillColor(...lightGrey)
  doc.rect(15, 63, pageW - 30, 18, 'F')
  doc.setTextColor(...darkText)
  doc.setFontSize(9)
  doc.setFont('helvetica', 'normal')
  doc.text(`Class: ${childInfo.childClass}   |   Board: ${childInfo.childBoard}`, pageW / 2, 74, { align: 'center' })

  // Profile description
  doc.setFontSize(11)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(...navy)
  doc.text('Your Profile', 15, 92)

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(9)
  doc.setTextColor(...darkText)
  const descLines = doc.splitTextToSize(result.profile.description, pageW - 30)
  doc.text(descLines, 15, 100)

  let y = 100 + descLines.length * 5 + 8

  // Category scores
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(11)
  doc.setTextColor(...navy)
  doc.text('Category Breakdown', 15, y)
  y += 8

  result.categoryScores.forEach((cat) => {
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(9)
    doc.setTextColor(...darkText)
    doc.text(cat.category, 15, y)
    doc.text(`${cat.percentage}%`, pageW - 15, y, { align: 'right' })

    // Bar background
    doc.setFillColor(220, 220, 230)
    doc.roundedRect(15, y + 2, pageW - 30, 4, 1, 1, 'F')

    // Bar fill
    const fillColor = cat.percentage >= 73 ? [41, 128, 185] : cat.percentage >= 40 ? [243, 156, 18] : [231, 76, 60]
    doc.setFillColor(...(fillColor as [number, number, number]))
    const fillW = Math.max(2, ((pageW - 30) * cat.percentage) / 100)
    doc.roundedRect(15, y + 2, fillW, 4, 1, 1, 'F')

    y += 14
  })

  y += 4

  // Strengths
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(11)
  doc.setTextColor(...navy)
  doc.text('Your Strengths', 15, y)
  y += 7

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(9)
  doc.setTextColor(...darkText)
  result.profile.strengths.forEach((s) => {
    doc.text(`• ${s}`, 18, y)
    y += 6
  })

  y += 4

  // Areas to improve
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(11)
  doc.setTextColor(...navy)
  doc.text('Areas for Growth', 15, y)
  y += 7

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(9)
  doc.setTextColor(...darkText)
  result.profile.improvements.forEach((s) => {
    doc.text(`• ${s}`, 18, y)
    y += 6
  })

  // Footer
  doc.setFillColor(...navy)
  doc.rect(0, 277, pageW, 20, 'F')
  doc.setTextColor(...white)
  doc.setFontSize(8)
  doc.setFont('helvetica', 'normal')
  doc.text('Generated by Immpact — Parent Career Guidance Assessment', pageW / 2, 289, { align: 'center' })

  doc.save('Immpact-Report.pdf')
}
